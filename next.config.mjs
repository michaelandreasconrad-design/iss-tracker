// Die Content Security Policy (mit Nonce pro Anfrage) setzt middleware.js.
// Hier stehen die Header, die für alle Pfade gleich sind, auch für statische Dateien.
/** @type {import('next').NextConfig} */
const nextConfig = {
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'X-Frame-Options', value: 'DENY' },
          { key: 'X-Content-Type-Options', value: 'nosniff' },
        ],
      },
    ];
  },
};

export default nextConfig;
